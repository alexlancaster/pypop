@pytest.mark.parametrize(
    "allele_data",
    [
        pytest.param(allele_data_90, id="90-alleles"),
        pytest.param(allele_data_100, id="100-alleles"),
        pytest.param(
            allele_data_101, marks=pytest.mark.xfail(strict=False), id="101-alleles"
        ),
        pytest.param(
            allele_data_110, marks=pytest.mark.xfail(strict=False), id="110-alleles"
        ),
        pytest.param(
            allele_data_211, marks=pytest.mark.xfail(strict=False), id="211-alleles"
        ),
    ],
)
def test_homozygosity_bounds_with_many_alleles(allele_data):
    """Test homozygosity statistics with many distinct alleles."""
    homozygosity = HomozygosityEWSlatkinExact(
        alleleData=allele_data,
        numReplicates=10000,
    )
    homozygosity.doCalcs(allele_data)
    print("Expected F: ", homozygosity.mean_homozygosity)

    assert 0.0 < homozygosity.mean_homozygosity <= 1.0
    # assert -1.0 <= homozygosity.getNormDevHomozygosity() <= 1.0
